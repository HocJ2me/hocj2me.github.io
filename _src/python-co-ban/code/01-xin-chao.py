# Chương trình Python đầu tiên
# Dòng bắt đầu bằng dấu # là chú thích: Python bỏ qua, chỉ để người đọc hiểu.

print("Xin chào, Python!")
print("Mình đang học lập trình", "cùng thầy Tuyền")      # print in nhiều giá trị, cách nhau bởi dấu cách
print()                                                  # in một dòng trống

# Python là một chiếc máy tính bỏ túi rất mạnh
print("2 + 3 =", 2 + 3)
print("7 / 2 =", 7 / 2)        # chia ra số thực
print("7 // 2 =", 7 // 2)      # chia lấy phần nguyên
print("7 % 2 =", 7 % 2)        # chia lấy dư
print("2 ** 10 =", 2 ** 10)    # lũy thừa
print("2 ** 100 =", 2 ** 100)  # số nguyên Python lớn bao nhiêu cũng được!

# In nhiều dòng và ký tự đặc biệt
print("Dòng 1\nDòng 2\tcó tab")
print("=" * 30)                # nhân chuỗi với số
print("Python được đặt tên theo nhóm hài Monty Python, không phải con trăn 🐍")
